export function translate(lang, key) {
  const parts = key.split('.')
  let value = translations[lang] || translations.en
  for (const part of parts) {
    value = value?.[part]
  }
  if (value == null) {
    value = translations.en
    for (const part of parts) {
      value = value?.[part]
    }
  }
  return value ?? key
}
