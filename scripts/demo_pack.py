"""Build the stored demo content pack through the live API.

Every item is generated by a real provider (Gemini is disabled by env) and
persisted by the API itself, so the demo replays stored artefacts instead of
waiting on live latency.

Writes JSON artefacts to docs/demo-pack/ and prints the stored ids/titles.
"""
from __future__ import annotations

import concurrent.futures as cf
import json
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000").rstrip("/")
OUT = Path(__file__).resolve().parent.parent / "docs" / "demo-pack"
OUT.mkdir(parents=True, exist_ok=True)
SESSION_ID = 3  # instructor session the demo student is enrolled in ("Ai")
KB_FILE = "ECU-ITAI-3-04.pdf"


def call(path: str, payload=None, token=None, method="POST", timeout=300):
    data = None if payload is None else json.dumps(payload).encode()
    req = urllib.request.Request(
        BASE + path, data=data,
        headers={"Content-Type": "application/json",
                 **({"Authorization": f"Bearer {token}"} if token else {})},
        method=method)
    started = time.time()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            raw = r.read()
            return r.status, raw, time.time() - started
    except urllib.error.HTTPError as e:
        return e.code, e.read(), time.time() - started
    except Exception as e:  # noqa: BLE001 - network/timeout
        return 0, str(e).encode(), time.time() - started


def jcall(path, payload=None, token=None, method="POST", timeout=300):
    status, raw, secs = call(path, payload, token, method, timeout)
    try:
        body = json.loads(raw.decode())
    except Exception:
        body = raw.decode(errors="replace")[:400]
    return status, body, secs


def save(name: str, obj) -> Path:
    path = OUT / name
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


def main() -> int:
    log = []
    status, body, _ = jcall("/api/auth/login",
                            {"email": "instructor@edusense.local", "password": "Password123"})
    if status != 200:
        print("LOGIN FAILED", status, body)
        return 1
    token = body["access_token"]
    sstatus, sbody, _ = jcall("/api/auth/login",
                              {"email": "student@edusense.local", "password": "Password123"})
    student = sbody["access_token"] if sstatus == 200 else None

    def lesson_en():
        return ("lesson-en",) + jcall("/api/ai/lessons", {
            "topic": "Neural Networks", "prompt": "", "language": "English",
            "teaching_style": "Friendly", "detail_level": "Standard",
            "session_id": SESSION_ID}, token)

    def lesson_ar():
        return ("lesson-ar",) + jcall("/api/ai/lessons", {
            "topic": "الشبكات العصبية", "prompt": "", "language": "Arabic",
            "teaching_style": "Friendly", "detail_level": "Standard",
            "session_id": SESSION_ID}, token)

    def quiz():
        return ("quiz",) + jcall("/api/ai/quizzes", {
            "topic": "Neural Networks", "prompt": "", "difficulty": "Medium",
            "count": 5, "session_id": SESSION_ID}, token)

    def cards():
        # Ask for 8; if the model returns fewer, ask once more for the gap and
        # deduplicate. Never invent a card to reach the number.
        status_, got, secs = jcall("/api/ai/flashcards", {
            "topic": "Neural Networks", "count": 8, "language": "English",
            "session_id": SESSION_ID}, token)
        if status_ != 200:
            return "flashcards", status_, got, secs
        merged = list(got.get("cards") or [])
        attempts = [(status_, got, secs)]
        rounds = 0
        while len(merged) < 8 and rounds < 2:
            rounds += 1
            missing = 8 - len(merged)
            st, extra, sc = jcall("/api/ai/flashcards", {
                "topic": "Neural Networks", "count": max(3, missing + 2),
                "language": "English",
                "prompt": f"Produce {missing} additional flashcards on a different "
                          f"aspect of neural networks than these: "
                          f"{'; '.join((c.get('front') or '')[:60] for c in merged)}"},
                token)
            attempts.append((st, extra, sc))
            if st != 200:
                break
            seen = {(c.get("front") or "").strip().lower() for c in merged}
            for c in extra.get("cards") or []:
                key = (c.get("front") or "").strip().lower()
                if key and key not in seen:
                    merged.append(c)
                    seen.add(key)
                if len(merged) >= 8:
                    break
        got["cards"] = merged[:8]
        got["requested"] = 8
        got["rounds"] = len(attempts)
        got["timings"] = [round(a[2], 1) for a in attempts]
        got["counts"] = [len(a[1].get("cards") or []) for a in attempts if isinstance(a[1], dict)]
        return "flashcards", status_, got, secs

    def kb_normal():
        return ("kb-q1-normal",) + jcall("/api/rag/ask", {
            "question": "What does the document say about concept drift detection?",
            "source_file": KB_FILE}, token)

    def kb_passage():
        return ("kb-q2-passage",) + jcall("/api/rag/ask", {
            "question": "Explain this passage from the document: \"Statistical tests "
                        "for detecting drift ... Relying solely\"",
            "source_file": KB_FILE}, token)

    def kb_page():
        return ("kb-q3-page",) + jcall("/api/rag/ask", {
            "question": "What is on page 58 of this document?",
            "source_file": KB_FILE}, token)

    def chat():
        return ("webchat",) + jcall("/api/ai/chat", {
            "message": "What is backpropagation and why is it used in neural networks?"},
            token)

    jobs = [lesson_en, lesson_ar, quiz, cards, kb_normal, kb_passage, kb_page, chat]
    results = {}
    with cf.ThreadPoolExecutor(max_workers=3) as pool:
        futures = {pool.submit(fn): fn.__name__ for fn in jobs}
        for fut in cf.as_completed(futures):
            name, status_, body, secs = fut.result()
            results[name] = body
            if status_ == 200 and isinstance(body, dict):
                save(f"{name}.json", body)
                print(f"{name:16s} {status_} {secs:6.1f}s  saved")
            else:
                print(f"{name:16s} {status_} {secs:6.1f}s  FAILED {str(body)[:200]}")
            log.append((name, status_, round(secs, 1)))

    # ── quiz → published exam for the demo session ────────────────────────
    q = results.get("quiz") or {}
    if q.get("id"):
        st, exam, secs = jcall(f"/api/quizzes/{q['id']}/publish-as-exam", {
            "session_id": SESSION_ID, "is_published": True,
            "time_limit_seconds": 600, "fullscreen_lock": True,
            "camera_monitoring": False, "reveal_answers": True}, token)
        print(f"{'publish-exam':16s} {st} {secs:6.1f}s  "
              f"is_exam={exam.get('is_exam')} published={exam.get('is_published')} "
              f"session={exam.get('session_id')} questions={len(exam.get('questions') or [])}")
        save("quiz-exam.json", exam if isinstance(exam, dict) else {"raw": str(exam)})
        log.append(("publish-exam", st, round(secs, 1)))
        if student:
            st2, exams, secs2 = jcall("/api/quizzes/student/exams", None, student, "GET")
            seen = [e.get("title") for e in exams] if isinstance(exams, list) else exams
            print(f"{'student exams':16s} {st2} {secs2:6.1f}s  {seen}")
            log.append(("student exams", st2, round(secs2, 1)))

    # ── stored versions (the ids the demo page lists) ─────────────────────
    st, gens, _ = jcall("/api/ai/generations", None, token, "GET")
    if st == 200 and isinstance(gens, list):
        print("\nstored generations (newest first):")
        for g in gens[:12]:
            print(f"  id={g.get('id'):<5} type={g.get('type'):<11} topic={str(g.get('topic'))[:40]}")

    save("_run.json", {"base": BASE, "session_id": SESSION_ID, "steps": log})
    print("\nartefacts written to", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
